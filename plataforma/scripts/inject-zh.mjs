function zhFor(en) {
  if (MAP[en]) return MAP[en];
  const trimmed = en.trim();
  if (MAP[trimmed]) return MAP[trimmed];
  return en;
}

function findCalls(src, name) {
  const out = [];
  const needle = name + '(';
  let i = 0;
  while (i < src.length) {
    const idx = src.indexOf(needle, i);
    if (idx < 0) break;
    if (idx > 0 && /[A-Za-z0-9_]/.test(src[idx - 1])) { i = idx + 1; continue; }
    const startArgs = idx + needle.length;
    let depth = 1, j = startArgs, inStr = null, esc = false;
    while (j < src.length && depth) {
      const c = src[j];
      if (inStr) {
        if (esc) esc = false;
        else if (c === '\\') esc = true;
        else if (c === inStr) inStr = null;
      } else if (c === "'" || c === '"') inStr = c;
      else if (c === '(') depth++;
      else if (c === ')') depth--;
      j++;
    }
    out.push({ start: idx, end: j, inner: src.slice(startArgs, j - 1) });
    i = j;
  }
  return out;
}

function splitArgs(inner) {
  const args = [];
  let cur = '', depth = 0, inStr = null, esc = false;
  for (let i = 0; i < inner.length; i++) {
    const c = inner[i];
    if (inStr) {
      cur += c;
      if (esc) esc = false;
      else if (c === '\\') esc = true;
      else if (c === inStr) inStr = null;
    } else if (c === "'" || c === '"') { inStr = c; cur += c; }
    else if (c === '(' || c === '[' || c === '{') { depth++; cur += c; }
    else if (c === ')' || c === ']' || c === '}') { depth--; cur += c; }
    else if (c === ',' && depth === 0) { args.push(cur.trim()); cur = ''; }
    else cur += c;
  }
  if (cur.trim()) args.push(cur.trim());
  return args;
}

function unquote(s) {
  if (!s || (s[0] !== "'" && s[0] !== '"')) return null;
  const q = s[0];
  if (s[s.length - 1] !== q) return null;
  let out = '';
  for (let i = 1; i < s.length - 1; i++) {
    if (s[i] === '\\' && i + 1 < s.length - 1) { out += s[i + 1]; i++; }
    else out += s[i];
  }
  return out;
}

function quote(s) {
  return "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
}

function inject(src, fnName) {
  const calls = findCalls(src, fnName);
  let missing = 0;
  let added = 0;
  const replacements = [];
  for (const call of calls) {
    const args = splitArgs(call.inner);
    if (args.length !== 4) continue;
    const en = unquote(args[1]);
    if (en == null) continue;
    const zh = zhFor(en);
    if (zh === en && !/^[\w .&/°+\-–—’'()]+$/.test(en) && en.length > 18) missing++;
    const inner = args[0] + ',\n      ' + args[1] + ',\n      ' + args[2] + ',\n      ' + args[3] + ',\n      ' + quote(zh);
    replacements.push({ start: call.start, end: call.end, text: fnName + '(' + inner + ')' });
    added++;
  }
  for (const r of replacements.reverse()) src = src.slice(0, r.start) + r.text + src.slice(r.end);
  return { src, added, missing };
}

