export function t(lang, path) {
  const parts = path.split('.');
  const read = (pack) => parts.reduce((o, p) => (o == null ? o : o[p]), pack);
  return read(I18N[lang]) ?? read(I18N.pt) ?? path;
}

export function loc(item, lang) {
  if (!item) return '';
  if (typeof item === 'string') return item;
  return item[lang] || item.pt || '';
}
