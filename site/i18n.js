  function get(obj, path) {
    return path.split('.').reduce((o, k) => (o == null ? o : o[k]), obj);
  }
  function t(key, vars) {
    const node = get(D, key);
    let s = (node && (node[lang] || node.pt)) || key;
    if (vars) s = String(s).replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? '' : vars[k]));
    return s;
  }
  function loc(obj) {
    if (!obj) return '';
    if (typeof obj === 'string') return obj;
    return obj[lang] || obj.pt || obj.name || '';
  }
  function slideFor(img) {
    const key = String(img || '').replace(/^.*\//, '');
    const s = SLIDES[key];
    if (!s) return null;
    return { t: s.t[lang] || s.t.pt, tag: s.tag[lang] || s.tag.pt, q: s.q[lang] || s.q.pt, m: s.m[lang] || s.m.pt };
  }
  function setTextNode(el, text) {
    const n = [...el.childNodes].find((x) => x.nodeType === 3 && x.textContent.trim());
    if (n) n.textContent = text;
    else el.insertBefore(document.createTextNode(text), el.firstChild);
  }
  function applyDom() {
    document.documentElement.lang = LOCALES[lang] || lang;
    document.title = t('title');
    const meta = document.querySelector('meta[name="description"]');
    if (meta) meta.setAttribute('content', t('desc'));
    document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    document.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder)); });
    document.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => { el.setAttribute('title', t(el.dataset.i18nTitle)); });
    document.querySelectorAll('[data-i18n-label]').forEach((el) => { setTextNode(el, t(el.dataset.i18nLabel)); });
    document.querySelectorAll('[data-p-i18n]').forEach((el) => {
      const title = t(el.dataset.pI18n);
      const q = el.dataset.pI18nQ ? t(el.dataset.pI18nQ) : '';
      el.dataset.pT = title;
      el.dataset.pQ = q;
      el.setAttribute('aria-label', t('esp.zoom', { n: title }));
      const img = el.querySelector('img');
      if (img) img.alt = title;
    });
    document.querySelectorAll('#langBar [data-lang]').forEach((b) => b.classList.toggle('on', b.dataset.lang === lang));
    const flag = document.getElementById('langFlag');
    if (flag) {
      const changed = flag.dataset.flag !== lang;
      flag.dataset.flag = lang;
      if (changed) {
        flag.classList.remove('pop');
        void flag.offsetWidth;
        flag.classList.add('pop');
      }
    }
    const bar = document.getElementById('langBar');
    if (bar) bar.classList.remove('open');
    const toggle = bar && bar.querySelector('.lang-btn');
    if (toggle) toggle.setAttribute('aria-expanded', 'false');
  }
  function setLang(next) {
    if (!LANGS.includes(next)) return;
    lang = next;
    try { localStorage.setItem('aqua_lang', lang); } catch (e) { /* */ }
    applyDom();
    listeners.forEach((fn) => fn(lang));
  }
  function bootBar() {
    const bar = document.getElementById('langBar');
    const btn = bar && bar.querySelector('.lang-btn');
    const close = () => {
      if (!bar) return;
      bar.classList.remove('open');
      if (btn) btn.setAttribute('aria-expanded', 'false');
    };
    const open = () => {
      if (!bar) return;
      bar.classList.add('open');
      if (btn) btn.setAttribute('aria-expanded', 'true');
    };
    if (btn) {
      btn.addEventListener('click', (e) => {
        e.stopPropagation();
        bar.classList.contains('open') ? close() : open();
      });
      document.addEventListener('click', (e) => { if (!bar.contains(e.target)) close(); });
      document.addEventListener('keydown', (e) => { if (e.key === 'Escape') close(); });
    }
    document.querySelectorAll('#langBar [data-lang]').forEach((b) => {
      b.addEventListener('click', () => setLang(b.dataset.lang));
    });
    applyDom();
  }

  window.AquaI18n = {
    t, loc, setLang, applyDom, slideFor,
    lang: () => lang,
    locale: () => LOCALES[lang] || 'pt-PT',
    onChange(fn) { listeners.push(fn); }
  };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', bootBar);
  else bootBar();
